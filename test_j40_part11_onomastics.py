def search_gen_data(query):
    q = query.strip().lower()
    if not q:
        return []
    words = [w for w in q.split() if w not in ['wdowa', 'sukcesor', 'sukcesorowie', 'z', 'plac', 'pusty', 'pole', 'ogród', 'żona', 'synem', 'dziećmi', 'żyd', 'sławetny', 'uczciwy', 'starszy', 'wtóry', 'drugi', 'wpis/ogród']]
    if not words:
        words = q.split()
    hits = []
    for d in gen_data:
        searchable_parts = [
            str(d.get('lp', '')),
            d.get('nazwisko', ''),
            d.get('imie', ''),
            d.get('miejsce', ''),
            d.get('funkcja', ''),
            d.get('wariant_nazwiska', ''),
            d.get('uwagi', '')
        ]
        blob = " ".join(p for p in searchable_parts if p).lower()
        if all(w in blob for w in words):
            hits.append(d)
    return hits

